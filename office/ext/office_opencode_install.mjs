import { lstatSync, readFileSync, realpathSync, mkdirSync, writeFileSync, renameSync, linkSync, unlinkSync } from 'node:fs';
import { isAbsolute, join } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { randomUUID } from 'node:crypto';
import { homedir } from 'node:os';
import { releaseVersion } from './office_pi_round.mjs';

const marker = '// Generated by Office: OpenCode 2 entry.\n';
const entryText = (path, home) => home
  ? `${marker}import { createOfficePlugin } from ${JSON.stringify(path)};\nexport default createOfficePlugin(${JSON.stringify(home)});\n`
  : `${marker}export { default } from ${JSON.stringify(path)};\n`;

export function installOpenCode(project, home = '') {
  if (home && !isAbsolute(home)) throw new Error('Office home 必须是绝对路径');
  const source = realpathSync(fileURLToPath(new URL('../opencode/postoffice.ts', import.meta.url)));
  const stable = home && join(home, 'runtime/office/opencode/postoffice.ts');
  const release = releaseVersion(pathToFileURL(source).href);
  if (!release) throw new Error('只能安装带有效 DEPLOY_SOURCE.json 的固定发布包');
  const global = !project;
  const plugins = global
    ? join(process.env.XDG_CONFIG_HOME || join(homedir(), '.config'), 'opencode', 'plugins', 'office-postoffice')
    : join(realpathSync(project), '.opencode', 'plugins');
  const target = join(plugins, global ? 'index.ts' : 'office-postoffice.ts');
  mkdirSync(plugins, {recursive: true});
  let previous = null;
  try {
    if (!lstatSync(target).isFile()) throw new Error('同名入口不是普通文件，保留原文件');
    previous = readFileSync(target, 'utf8');
    const existing = global && previous.startsWith('import {createOfficePlugin} from ')
      ? marker + previous.replace('{createOfficePlugin}', '{ createOfficePlugin }') : previous;
    const match = /^\/\/ Generated by Office: OpenCode 2 entry\.\n(?:export \{ default \} from ("(?:[^"\\]|\\.)*");|import \{ createOfficePlugin \} from ("(?:[^"\\]|\\.)*");\nexport default createOfficePlugin\(("(?:[^"\\]|\\.)*")\);)\n$/.exec(existing);
    let oldPath, oldHome;
    try { oldPath = match && JSON.parse(match[1] || match[2]); oldHome = match?.[3] && JSON.parse(match[3]); } catch { /* foreign */ }
    if (typeof oldPath !== 'string' || !oldPath.startsWith('/') || !oldPath.endsWith('/office/opencode/postoffice.ts') || (oldHome && !isAbsolute(oldHome)) || existing !== entryText(oldPath, oldHome))
      throw new Error('同名入口不是 Office 生成的文件，保留原文件');
  } catch (e) { if (e.code !== 'ENOENT') throw e; }
  const content = entryText(global && stable && releaseVersion(pathToFileURL(stable).href)?.version === release.version ? stable : source, home);
  if (previous === content) return {ok: true, state: 'unchanged', path: target, version: release.version};
  const temporary = join(plugins, `.office-postoffice-${randomUUID()}.tmp`);
  try {
    writeFileSync(temporary, content, {flag: 'wx', mode: 0o644});
    if (previous === null) { linkSync(temporary, target); unlinkSync(temporary); }
    else renameSync(temporary, target);
  } finally { try { unlinkSync(temporary); } catch (e) { if (e.code !== 'ENOENT') throw e; } }
  return {ok: true, state: previous === null ? 'installed' : 'upgraded', path: target, version: release.version};
}
